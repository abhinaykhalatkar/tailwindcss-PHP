/**
 * The independent T1 inventory (decision ENG-A12, review R-0001 finding 1).
 *
 * Every T1 root of design doc 08 §Utilities, written by hand, one entry per root.
 *
 * **This file is the denominator of the 98 % gate, so it must never be derived from
 * the implementation.** If the corpus were generated from `Engine\Data\Utilities`
 * alone, a utility forgotten there would vanish from the code and from the tests at
 * once. Do not generate this file from `Data/Utilities`, do not import anything from
 * `src/Engine` here, and when doc 08 changes, change this file by hand in the same
 * pull request. `tests/Unit/Conformance/Support/InventoryTest` pins the per-family
 * counts as literals, so a silent deletion fails loudly.
 *
 * Entry schema (the contract TASK-0035 consumes — keep it exactly):
 *
 *   family     one of: layout, flexbox-grid, spacing-sizing, typography,
 *              backgrounds-borders, effects-filters, tables-transitions-transforms,
 *              interactivity-svg-accessibility, arbitrary-property
 *   kind       static (a fixed utility such as `hidden`) | functional (takes a value)
 *   theme      theme namespaces a value can be named from, as written in doc 08
 *   bare       how an unadorned value reads: spacing-multiplier | integer | percentage |
 *              angle | duration | line-count | keyword | null (design doc 07 §Value
 *              resolution rules). Keyword-only roots are `keyword`; roots with both a
 *              number and extra keywords (`w-4`, `w-full`) are listed by the number.
 *   fraction   whether `1/2` is a value
 *   negative   whether a leading `-` is accepted (doc 08's ➖)
 *   arbitrary  whether `[...]` and `(--var)` are accepted (doc 08's ✗ means false)
 *   modifier   opacity | line-height | null. `text` takes both; it is listed as
 *              line-height, and its colour opacity is covered by the corpus.
 *   tier       always T1 here; T2 and T3 rows are deliberately absent
 *   forms      the candidate forms that count toward the 98 % for this root, from
 *              static, theme, bare, fraction, arbitrary, var, negative, important,
 *              modifier. A functional root that is also valid on its own (`border`,
 *              `rounded`, `flex`) carries `static` as well.
 *
 * Reading doc 08:
 *   - A root named in several rows is listed once, in the family of its first mention
 *     (`flex` in layout, `content` in flexbox-grid).
 *   - The last doc 08 table is split over the three last families: effects-filters,
 *     tables-transitions-transforms, interactivity-svg-accessibility.
 *   - Mixed-tier rows keep only their T1 roots. Transforms: rotate, scale, translate,
 *     origin, transform are T1; 3D, perspective and skew are T2. Interactivity:
 *     cursor, pointer-events, select, resize, appearance, scroll-*, snap-*, touch-*
 *     are T1; accent, caret, color-scheme, field-sizing, will-change are T2.
 *     Gradients: only bg-gradient-to-* and bg-linear-to-* are T1.
 *   - Doc 08 lists families of statics with a wildcard (snap-*, touch-*): the members
 *     are written out, and every static root was checked to be accepted by the pinned
 *     4.1.18 CLI.
 *   - The flags were cross-checked against the pinned CLI (fraction, negative,
 *     arbitrary and the numeric bare kinds). Where the CLI is narrower than doc 08's
 *     blanket "every row accepts arbitrary values" (justify, items, overflow, ...),
 *     the entry says false.
 */

