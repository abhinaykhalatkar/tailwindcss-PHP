    /**
     * The family names, in doc 08 order.
     *
     * @return list<string>
     */
    public function families(): array
    {
        return \array_map('strval', \array_keys($this->inventory->families()));
    }

    /**
     * Where a family's file is: always `<directory>/<family>.txt`, with the
     * family validated against the list.
     *
     * @throws \InvalidArgumentException When `$family` is not one of {@see self::families()}.
     */
    public function path(string $family): string
    {
        if (!\in_array($family, $this->families(), true)) {
            throw new \InvalidArgumentException('Unknown family "' . self::printable($family) . '".');
        }

        return $this->directory . '/' . $family . '.txt';
    }

    /**
     * Whether a file's text is one this generator wrote: its first line is the header.
     */
    public static function isGenerated(string $contents): bool
    {
        $end = \strpos($contents, "\n");
        $first = $end === false ? $contents : \substr($contents, 0, $end);

        return $first === self::HEADER;
    }

    /**
     * The text of a family's file.
     */
    public function render(string $family): string
    {
        $text = self::HEADER . "\n";

        foreach ($this->inventory->families()[$family] ?? [] as $root) {
            $text .= '# ' . $root . "\n";

            foreach ($this->lines($root) as $line) {
                $text .= $line . "\n";
            }
        }

        return $text;
    }

    /**
     * Every candidate line for a root, forms in canonical order then the
     * variant combinations, without duplicates.
     *
     * @return list<string>
     */
    public function lines(string $root): array
    {
        $lines = [];

        foreach ($this->linesByForm($root) as $formLines) {
            foreach ($formLines as $line) {
                $lines[$line] = true;
            }
        }

        return \array_map('strval', \array_keys($lines));
    }

    /**
     * The lines of each form (the nine of the inventory plus `variant`).
     *
     * @return array<string, list<string>>
     *
     * @throws \LogicException When a root needs a table entry that is missing.
     */
    public function linesByForm(string $root): array
    {
        $entry = $this->inventory->entry($root);
        $forms = $this->inventory->expectedForms($root);
        $property = $root === Inventory::ARBITRARY_PROPERTY;
        $by = [];

        foreach (self::FORM_ORDER as $form) {
            $by[$form] = [];
        }

        $by['variant'] = [];

        $bare = \in_array('bare', $forms, true) ? $this->bareSamples($root, $entry) : [];
        $theme = \in_array('theme', $forms, true) ? $this->themeSamples($entry) : [];
        $arbitrary = \in_array('arbitrary', $forms, true) ? $this->arbitrarySamples($root, $entry) : [];

        if (\in_array('static', $forms, true)) {
            $by['static'] = [$root];
        }

        foreach ($theme as $keys) {
            foreach ($keys as $key) {
                $by['theme'][] = $root . '-' . $key;
            }
        }

        foreach ($bare as $sample) {
            $by['bare'][] = $root . '-' . $sample;
        }

        if (\in_array('fraction', $forms, true)) {
            foreach (self::FRACTIONS as $fraction) {
                $by['fraction'][] = $root . '-' . $fraction;
            }
        }

        foreach ($arbitrary as $sample) {
            $by['arbitrary'][] = $property ? $sample : $root . '-[' . $sample . ']';
        }

        if (\in_array('var', $forms, true)) {
            $by['var'][] = $root . '-' . self::VARIABLE;
        }

        if (\in_array('negative', $forms, true)) {
            $by['negative'] = $this->negatives($root, $entry, $bare, $theme);
        }

        $representative = $this->representative($root, $forms, $bare, $by);

        if (\in_array('important', $forms, true) && $representative !== null) {
            $by['important'] = [$representative . '!'];
        }

        if (\in_array('modifier', $forms, true)) {
            $by['modifier'] = $this->modifiers($root, $entry, $theme);
        }

        if ($representative !== null) {
            foreach (self::COMBINATIONS as $variants) {
                $by['variant'][] = $variants . $representative;
            }
        }

        return $by;
    }

    /**
     * Write (or, with `$check`, compare) the files of one family or of all of them.
     *
     * Every file is built and every existing file checked before anything is
     * written, so a refusal part-way through leaves nothing half done.
     *
     * Statuses: `written`, `unchanged`, `drift` and `missing` (the last two only
     * in check mode, where nothing is written).
     *
     * @param string|null $only A family name; null for all of them.
     *
     * @return list<array{family: string, file: string, status: string, lines: int}>
     *
     * @throws \InvalidArgumentException When `$only` is not a family.
     * @throws \RuntimeException When a file exists that this generator did not write.
     */
    public function run(?string $only, bool $check): array
    {
        $families = $this->families();

        if ($only !== null && !\in_array($only, $families, true)) {
            throw new \InvalidArgumentException(\sprintf(
                '--only must be one of the families (%s); "%s" is not one.',
                \implode(', ', $families),
                self::printable($only)
            ));
        }

        $plan = [];

        foreach ($only === null ? $families : [$only] as $family) {
            $path = $this->path($family);
            $text = $this->render($family);
            $existing = \is_file($path) ? (string) \file_get_contents($path) : null;

            if ($existing !== null && !self::isGenerated($existing)) {
                throw new \RuntimeException(
                    'Refusing to overwrite the corpus file of family "' . $family . '": it is not generated.'
                );
            }

            $plan[] = ['family' => $family, 'path' => $path, 'text' => $text, 'existing' => $existing];
        }

        $results = [];

        foreach ($plan as $item) {
            $results[] = [
                'family' => $item['family'],
                'file' => 'utilities/' . $item['family'] . '.txt',
                'status' => $this->settle($item['path'], $item['text'], $item['existing'], $check),
                'lines' => self::countLines($item['text']),
            ];
        }

        return $results;
    }

    /**
     * Whether any file differs from, or is absent from, the committed tree.
     *
     * @param list<array{family: string, file: string, status: string, lines: int}> $results
     */
    public static function hasDrift(array $results): bool
    {
        foreach ($results as $result) {
            if ($result['status'] === 'drift' || $result['status'] === 'missing') {
                return true;
            }
        }

        return false;
    }

    private function settle(string $path, string $text, ?string $existing, bool $check): string
    {
        if ($existing === $text) {
            return 'unchanged';
        }

        if ($check) {
            return $existing === null ? 'missing' : 'drift';
        }

        $directory = \dirname($path);

        if (!\is_dir($directory) && !\mkdir($directory, 0777, true) && !\is_dir($directory)) {
            throw new \RuntimeException('Could not create the corpus directory.');
        }

        if (\file_put_contents($path, $text) === false) {
            throw new \RuntimeException('Could not write a corpus file.');
        }

        return 'written';
    }

    // ---------------------------------------------------------------- samples

    /**
     * @param array<string, mixed> $entry
     *
     * @return list<string>
     */
    private function bareSamples(string $root, array $entry): array
    {
        $kind = (string) ($entry['bare'] ?? '');

        if ($kind === 'keyword') {
            $samples = self::lookup(self::KEYWORDS, $root);

            if ($samples === null) {
                throw new \LogicException('No keyword samples for root "' . $root . '".');
            }

            return $samples;
        }

        $samples = self::lookup(self::BARE_OVERRIDES, $root) ?? self::BARE_BY_KIND[$kind] ?? [];

        return self::unique(\array_merge($samples, self::lookup(self::EXTRA_BARE, $root) ?? []));
    }

    /**
     * Theme keys by namespace, in the order they are used.
     *
     * @param array<string, mixed> $entry
     *
     * @return array<string, list<string>> Namespace pattern => keys.
     */
    private function themeSamples(array $entry): array
    {
        $samples = [];

        foreach ((array) ($entry['theme'] ?? []) as $namespace) {
            $namespace = (string) $namespace;

            $samples[$namespace] = $namespace === '--color-*'
                ? \array_merge(self::COLOUR_SPECIAL, $this->colourKeys())
                : $this->themeKeys($namespace);
        }

        return $samples;
    }

    /**
     * The black, white and palette shades the theme actually defines.
     *
     * @return list<string>
     */
    private function colourKeys(): array
    {
        $keys = [];

        foreach (self::COLOUR_THEME as $name) {
            if (isset($this->theme['--color-' . $name])) {
                $keys[] = $name;
            }
        }

        return $keys;
    }

    /**
     * At most {@see self::MAX_THEME_KEYS} keys of a namespace: all of them when
     * there are few, otherwise the first, the last and an even spread.
     *
     * @return list<string>
     */
    private function themeKeys(string $namespace): array
    {
        $prefix = \substr($namespace, 0, -1);
        $skip = self::THEME_SKIP[$prefix] ?? [];
        $keys = [];

        foreach (\array_keys($this->theme) as $name) {
            $name = (string) $name;

            if (\strncmp($name, $prefix, \strlen($prefix)) !== 0) {
                continue;
            }

            $key = (string) \substr($name, \strlen($prefix));

            if ($key === '' || \strpos($key, '--') !== false || self::startsWithAny($key, $skip)) {
                continue;
            }

            $keys[] = $key;
        }

        $count = \count($keys);

        if ($count <= self::MAX_THEME_KEYS) {
            return $keys;
        }

        $picked = [];

        for ($i = 0; $i < self::MAX_THEME_KEYS; ++$i) {
            $picked[] = $keys[\intdiv($i * ($count - 1), self::MAX_THEME_KEYS - 1)];
        }

        return $picked;
    }

    /**
     * @param array<string, mixed> $entry
     *
     * @return list<string>
     */
    private function arbitrarySamples(string $root, array $entry): array
    {
        if ($root === Inventory::ARBITRARY_PROPERTY) {
            return self::ARBITRARY_PROPERTY;
        }

        $own = self::lookup(self::ARBITRARY, $root);

        if ($own !== null) {
            return $own;
        }

        $kind = (string) ($entry['bare'] ?? '');

        if (isset(self::ARBITRARY_BY_KIND[$kind])) {
            return self::ARBITRARY_BY_KIND[$kind];
        }

        throw new \LogicException('No arbitrary samples for root "' . $root . '".');
    }

    /**
     * @param array<string, mixed> $entry
     * @param list<string> $bare
     * @param array<string, list<string>> $theme
     *
     * @return list<string>
     */
    private function negatives(string $root, array $entry, array $bare, array $theme): array
    {
        $kind = (string) ($entry['bare'] ?? '');
        $lines = [];

        if ($kind !== '' && $kind !== 'keyword') {
            foreach (self::BARE_BY_KIND[$kind] ?? [] as $sample) {
                if ($sample !== '0' && \in_array($sample, $bare, true)) {
                    $lines[] = '-' . $root . '-' . $sample;
                }
            }
        }

        if ($lines === []) {
            foreach ($theme as $keys) {
                foreach (\array_slice($keys, 0, 2) as $key) {
                    $lines[] = '-' . $root . '-' . $key;
                }

                break;
            }
        }

        if (!empty($entry['fraction'])) {
            $lines[] = '-' . $root . '-' . self::FRACTIONS[0];
        }

        return $lines;
    }

    /**
     * `/50` on the colour samples, `/7` on the size samples of a line-height root.
     *
     * @param array<string, mixed> $entry
     * @param array<string, list<string>> $theme
     *
     * @return list<string>
     */
    private function modifiers(string $root, array $entry, array $theme): array
    {
        $lines = [];

        foreach ($theme as $namespace => $keys) {
            if ($namespace === '--color-*') {
                foreach ($this->colourKeys() as $key) {
                    $lines[] = $root . '-' . $key . '/50';
                }

                continue;
            }

            if (($entry['modifier'] ?? null) === 'line-height') {
                foreach ($keys as $key) {
                    $lines[] = $root . '-' . $key . '/7';
                }
            }
        }

        return $lines;
    }

    /**
     * The one candidate combined with `!` and with the variants: the static root,
     * else the kind's representative bare sample, else the first theme or
     * arbitrary line.
     *
     * @param list<string> $forms
     * @param list<string> $bare
     * @param array<string, list<string>> $by
     */
    private function representative(string $root, array $forms, array $bare, array $by): ?string
    {
        if (\in_array('static', $forms, true)) {
            return $root;
        }

        if ($bare !== []) {
            $entry = $this->inventory->entry($root);
            $preferred = self::REPRESENTATIVE[(string) ($entry['bare'] ?? '')] ?? $bare[0];

            return $root . '-' . (\in_array($preferred, $bare, true) ? $preferred : $bare[0]);
        }

        foreach (['theme', 'arbitrary', 'fraction', 'var'] as $form) {
            if ($by[$form] !== []) {
                return $by[$form][0];
            }
        }

        return null;
    }

    // ---------------------------------------------------------------- helpers

    /**
     * The samples of the group a root belongs to, or null.
     *
     * @param list<array{0: list<string>, 1: list<string>}> $groups
     *
     * @return list<string>|null
     */
    private static function lookup(array $groups, string $root): ?array
    {
        foreach ($groups as $group) {
            if (\in_array($root, $group[0], true)) {
                return $group[1];
            }
        }

        return null;
    }

    /**
     * @param list<string> $values
     *
     * @return list<string>
     */
    private static function unique(array $values): array
    {
        return \array_values(\array_unique($values));
    }

    /**
     * @param list<string> $prefixes
     */
    private static function startsWithAny(string $text, array $prefixes): bool
    {
        foreach ($prefixes as $prefix) {
            if (\strncmp($text, $prefix, \strlen($prefix)) === 0) {
                return true;
            }
        }

        return false;
    }

    private static function countLines(string $text): int
    {
        $count = 0;

        foreach (\explode("\n", $text) as $line) {
            if ($line !== '' && $line[0] !== '#') {
                ++$count;
            }
        }

        return $count;
    }

    /**
     * A selector made safe to echo: at most 60 bytes, printable ASCII only.
     */
    private static function printable(string $text): string
    {
        $text = \strlen($text) > 60 ? \substr($text, 0, 60) : $text;
        $safe = '';

        for ($i = 0, $length = \strlen($text); $i < $length; ++$i) {
            $byte = \ord($text[$i]);
            $safe .= $byte >= 0x20 && $byte <= 0x7e ? $text[$i] : '?';
        }

        return $safe;
    }
