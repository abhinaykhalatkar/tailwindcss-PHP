/**
 * Builds the T1 utilities corpus from the independent inventory (design doc 08
 * §Acceptance thresholds; doc 16 §Corpus layout; decisions ENG-A10, ENG-A12).
 *
 * For every root of `tests/Conformance/inventory/t1.php` and every form in the
 * root's `forms` list it writes deterministic candidate lines: the static root, a
 * sample of theme keys, bare values by kind, fractions, arbitrary values, a
 * `(--var)`, negatives, an important form and a modifier. One representative
 * candidate per root is also combined with `md:`, `hover:`, `md:hover:`, `dark:`,
 * `group-hover:` and `[&>*]:` (about forty lines per functional root, as doc 08
 * budgets). The output is one file per inventory family, below
 * `tests/Conformance/corpus/utilities/`, and the goldens for them are produced by
 * `generate-goldens.php`, never here: this class does not run the CLI (T-04,
 * T-18).
 *
 * **The inventory is the input, never `src/Engine/Data`.** The corpus must not be
 * derived from the implementation it tests; the only engine data read is the
 * default theme, for the theme keys a candidate can name.
 *
 * **Hand-maintained tables.** What a value of a given kind looks like cannot be
 * read from the inventory, so the samples live in the tables below, written from
 * doc 08 and doc 07 §Phase 3b and checked against the pinned CLI: every generated
 * line must be one the CLI accepts, which `CorpusCoverageTest` enforces from the
 * golden. A keyword root, or an arbitrary-capable root whose values are not
 * plain numbers or lengths, without a table entry is a `\LogicException`
 * naming the root: a new inventory root cannot silently get no samples.
 *
 * **Safe by construction (T-01).** Files are written only below the corpus
 * directory the generator was given, named from {@see Inventory::FAMILIES}; the
 * `--only` selector is matched against that list and never joined to a path, and
 * a file that does not start with {@see self::HEADER} is never overwritten, so
 * the hand-written `edge-*.txt` files are safe. Errors name the family, never a
 * value.
 *
 * No regular expressions (R1 applies to `tools/` too). Lives under `tools/`:
 * maintainer tooling, not autoloaded, not shipped.
 */
